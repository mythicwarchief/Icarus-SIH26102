# ==========================================================
# GET HIGH-RISK ANOMALIES
# ==========================================================

@router.get(
    "/anomalies/high-risk",
    response_model=HighRiskAnomaliesResponse
)
def get_high_risk_anomalies(

    top_n: int = Query(
        default=10,
        ge=1,
        le=100
    ),
):

    try:

        anomalies = load_flagged_anomalies()

        if "anomaly_score" not in anomalies.columns:

            raise HTTPException(
                status_code=500,
                detail=(
                    "anomaly_score column "
                    "not found in anomaly output"
                )
            )

        high_risk = anomalies.sort_values(
            by="anomaly_score",
            ascending=False
        ).head(top_n)

        return {
            "count": len(high_risk),
            "data": dataframe_to_records(
                high_risk
            ),
        }

    except FileNotFoundError as error:

        raise HTTPException(
            status_code=404,
            detail=str(error)
        )


# ==========================================================
# GET SINGLE ANOMALY
# ==========================================================

@router.get(
    "/anomalies/{work_id:path}",
    response_model=AnomalyRecord
)
def get_anomaly_by_work_id(
    work_id: str
):

    try:

        anomalies = load_flagged_anomalies()

        result = anomalies[
            anomalies["work_id"] == work_id
        ]

        if result.empty:

            raise HTTPException(
                status_code=404,
                detail=(
                    f"No flagged anomaly found "
                    f"for work ID '{work_id}'"
                )
            )

        return dataframe_to_records(
            result
        )[0]

    except FileNotFoundError as error:

        raise HTTPException(
            status_code=404,
            detail=str(error)
        )