# ==========================================================
# GET ALL WORKS
# ==========================================================

@router.get(
    "/works",
    response_model=WorksResponse
)
def get_works(

    limit: int = Query(
        default=100,
        ge=1,
        le=1000
    ),

    offset: int = Query(
        default=0,
        ge=0
    ),
):

    df = load_features()

    total = len(df)

    # Standard pagination slice
    paginated_df = df.iloc[
        offset : offset + limit
    ]

    return {
        "total": total,
        "limit": limit,
        "offset": offset,
        "data": dataframe_to_records(
            paginated_df
        ),
    }


# ==========================================================
# GET SINGLE WORK
# ==========================================================

# IMPORTANT:
# work_id values contain "/" characters.
#
# Example:
# WS/MP005/2024-2025/145074
#
# Therefore we use {work_id:path} so FastAPI
# accepts the complete ID.

@router.get(
    "/works/{work_id:path}",
    response_model=WorkRecord
)
def get_work(work_id: str):

    df = load_features()

    work = get_work_by_id(
        df,
        work_id
    )

    if work is None:

        raise HTTPException(
            status_code=404,
            detail=(
                f"Work with ID "
                f"'{work_id}' was not found"
            )
        )

    # Convert safely to JSON
    return json.loads(
        pd.DataFrame([work]).to_json(
            orient="records",
            date_format="iso"
        )
    )[0]


