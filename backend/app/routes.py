ML_OUTPUT_DIR = PROJECT_ROOT / "ml" / "outputs"

ANOMALY_SCORES_FILE = (
    ML_OUTPUT_DIR / "anomaly_scores.csv"
)

ANOMALY_FLAGGED_FILE = (
    ML_OUTPUT_DIR / "anomaly_flagged.csv"
)

ANOMALY_SUMMARY_FILE = (
    ML_OUTPUT_DIR / "anomaly_summary.json"
)


# ==========================================================
# HELPER FUNCTIONS
# ==========================================================

def dataframe_to_records(df: pd.DataFrame):
    """
    Convert a DataFrame into JSON-safe records.
    Handles NaN values correctly.
    """

    return json.loads(
        df.to_json(
            orient="records",
            date_format="iso"
        )
    )


def load_anomaly_scores():
    """
    Load anomaly scores generated by the ML pipeline.
    """

    if not ANOMALY_SCORES_FILE.exists():

        raise FileNotFoundError(
            f"Anomaly scores file not found: "
            f"{ANOMALY_SCORES_FILE}"
        )

    return pd.read_csv(
        ANOMALY_SCORES_FILE
    )


def load_flagged_anomalies():
    """
    Load only flagged anomalies generated by the ML pipeline.
    """

    if not ANOMALY_FLAGGED_FILE.exists():

        raise FileNotFoundError(
            f"Flagged anomalies file not found: "
            f"{ANOMALY_FLAGGED_FILE}"
        )

    return pd.read_csv(
        ANOMALY_FLAGGED_FILE
    )


def load_anomaly_summary():
    """
    Load the ML pipeline summary JSON.
    """

    if not ANOMALY_SUMMARY_FILE.exists():

        raise FileNotFoundError(
            f"Anomaly summary file not found: "
            f"{ANOMALY_SUMMARY_FILE}"
        )

    with open(
        ANOMALY_SUMMARY_FILE,
        "r",
        encoding="utf-8"
    ) as file:

        return json.load(file)


